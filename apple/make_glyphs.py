"""Write apple/Common/HKGlyphs.swift: the house's own icons (`hk:` names) as the apps draw them.

Run: python3 apple/make_glyphs.py
The house's set (hosts/ha/custom_components/hk_frontend/tools/sf_symbols/manifest.json) names, for each `hk:` glyph,
the SF Symbol it is drawn from, or a path of its own (24-unit box) for the few that are not an SF Symbol. The apps
draw the symbol itself, or the path; a glyph whose path uses more than M L H V Q C Z is left out (the app's fallback
then). tests/test_apple_glyphs.py fails when this file and the manifest disagree.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE.parent / "hosts/ha/custom_components/hk_frontend/tools/sf_symbols/manifest.json"
OUT = HERE / "Common" / "HKGlyphs.swift"
DRAWN = set("MLHVQCZ")


def render() -> str:
    icons = json.loads(MANIFEST.read_text())["icons"]
    symbols, paths = [], []
    for name in sorted(icons):
        v = icons[name]
        if "symbol" in v:
            symbols.append(f'        "{name}": "{v["symbol"]}",')
        elif "path" in v and set(re.findall("[A-Za-z]", v["path"])) <= DRAWN:
            paths.append(f'        "{name}": "{v["path"]}",')
    return "\n".join([
        "// Generated by apple/make_glyphs.py from the house's icon set (hk_frontend/tools/sf_symbols/manifest.json).",
        "// Do not edit: run the script.",
        "",
        "enum HKGlyphs {",
        "    /// `hk:` name -> the SF Symbol it is drawn from.",
        "    static let symbols: [String: String] = [",
        *symbols,
        "    ]",
        "    /// `hk:` name -> its own drawing (SVG path data in a 24-unit box), for the glyphs that are not an SF Symbol.",
        "    static let paths: [String: String] = [",
        *paths,
        "    ]",
        "}",
        "",
    ])


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT}")
